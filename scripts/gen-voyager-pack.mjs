// Regenerates src/app/voyager-pack/packHtml.ts from the standalone demo file.
// Rewrites image paths to absolute /voyager-pack/, makes links break out of the
// iframe, and embeds the markup as base64 (so it is only ever sent to authorized
// users by the gated server component — never exposed as a public asset).
import { readFileSync, writeFileSync } from 'node:fs'

let html = readFileSync('membership-demo-en.html', 'utf8')

// absolute asset paths (iframe srcDoc has no usable base href)
html = html
  .replaceAll('voyager-hero.png', '/voyager-pack/voyager-hero.png')
  .replaceAll('badge-1.png', '/voyager-pack/badge-1.png')
  .replaceAll('badge-2.png', '/voyager-pack/badge-2.png')

// links (/voyagers, /vote) should navigate the whole window, not the iframe
html = html.replace('<head>', '<head>\n<base target="_top">')

const b64 = Buffer.from(html, 'utf8').toString('base64')
const out =
`// AUTO-GENERATED by scripts/gen-voyager-pack.mjs — do not edit by hand.
// Source: membership-demo-en.html. Re-run: node scripts/gen-voyager-pack.mjs
export const PACK_HTML = Buffer.from(
  '${b64}',
  'base64',
).toString('utf8')
`
writeFileSync('src/app/voyager-pack/packHtml.ts', out)
console.log('wrote src/app/voyager-pack/packHtml.ts (' + b64.length + ' b64 chars)')
